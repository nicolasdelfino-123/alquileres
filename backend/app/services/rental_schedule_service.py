"""Billing periods and explicit treatment of changes within a rental period."""
import calendar
from datetime import date, timedelta
from decimal import Decimal, ROUND_HALF_UP
from types import SimpleNamespace
from app.services.management_service import APIError


def cents(value):
    return value.quantize(Decimal('.01'), rounding=ROUND_HALF_UP)


def shift_month(day, months, anchor=None):
    year, month = divmod(day.year * 12 + day.month - 1 + months, 12)
    return date(year, month + 1, min(anchor or day.day, calendar.monthrange(year, month + 1)[1]))


def scheduled_next(contract, base, months):
    anchor = contract.start_date.day
    dates = sorted({a.effective_date for a in contract.adjustments if a.effective_date <= base} | {base})
    for day in dates:
        if day.day != min(anchor, calendar.monthrange(day.year, day.month)[1]):
            anchor = day.day
    try:
        return shift_month(base, months, anchor)
    except (ValueError, OverflowError):
        return None


def period_bounds(contract, year, month):
    cycle = getattr(contract, 'billing_cycle', None) or 'calendar'
    anchor = contract.start_date.day if cycle == 'anniversary' else 1
    try:
        start = date(year, month, min(anchor, calendar.monthrange(year, month)[1]))
        return start, shift_month(start, 1, anchor) - timedelta(days=1)
    except (ValueError, OverflowError):
        raise APIError('El período está fuera del rango de fechas admitido') from None


def containing_period(contract, day):
    start, end = period_bounds(contract, day.year, day.month)
    if day < start:
        previous = shift_month(day.replace(day=1), -1)
        start, end = period_bounds(contract, previous.year, previous.month)
    return start, end


def rent_on(contract, day):
    adjustments = sorted(contract.adjustments, key=lambda a: (a.effective_date, a.id or 0))
    applicable = [a for a in adjustments if a.effective_date <= day]
    return applicable[-1].new_amount if applicable else adjustments[0].previous_amount if adjustments else contract.current_rent


def treatment_for(contract, effective, treatment=None):
    start, _ = containing_period(contract, effective)
    treatment = treatment or getattr(contract, 'adjustment_billing_treatment', None)
    if treatment is None and effective == start:
        return 'prorate'
    if treatment not in {'prorate', 'whole_period', 'next_period'}:
        raise APIError('Elegí cómo se cobra el período del aumento: proporcional por días, nuevo importe completo o desde el próximo período.')
    return treatment


def switch_date(contract, effective, treatment):
    start, end = containing_period(contract, effective)
    if treatment == 'whole_period':
        return start
    if treatment == 'next_period' and effective != start:
        return end + timedelta(days=1)
    return effective


def validate_adjustment(contract, effective, treatment=None):
    if contract.status != 'active':
        raise APIError('El contrato no está activo', 409)
    if not contract.start_date < effective <= contract.end_date:
        raise APIError('La fecha del aumento debe ser posterior al inicio y estar dentro de la vigencia del contrato.')
    treatment = treatment_for(contract, effective, treatment)
    if any(a.effective_date >= effective for a in contract.adjustments):
        raise APIError('Ya hay un aumento en esa fecha o posterior. Revisá el historial antes de registrar otro.', 409)
    impact = max(contract.start_date, switch_date(contract, effective, treatment))
    for charge in contract.charges:
        if charge.cancelled_at:
            continue
        # Old charges were generated by calendar month, before period snapshots existed.
        end = charge.billing_end or date(charge.period_year, charge.period_month, calendar.monthrange(charge.period_year, charge.period_month)[1])
        if end >= impact:
            raise APIError('Ya hay mensualidades registradas que alcanza este aumento. No se cambian automáticamente; revisalas antes de continuar.', 409)
    return treatment


def calculate_rent(contract, year, month, extra=None):
    full_start, full_end = period_bounds(contract, year, month)
    start, end = max(full_start, contract.start_date), min(full_end, contract.end_date)
    if start > end:
        raise APIError('El período no corresponde al contrato')
    adjustments = sorted(contract.adjustments, key=lambda a: (a.effective_date, a.id or 0))
    base = adjustments[0].previous_amount if adjustments else contract.current_rent
    changes = []
    for adjustment in adjustments + ([extra] if extra else []):
        treatment = getattr(adjustment, 'billing_treatment', None) or 'prorate'
        changes.append((switch_date(contract, adjustment.effective_date, treatment), adjustment.effective_date, adjustment.new_amount))
    changes.sort(key=lambda row: (row[0], row[1]))
    rate = base
    for changed, _, value in changes:
        if changed <= start:
            rate = value
    boundaries = sorted({changed for changed, _, _ in changes if start < changed <= end}) + [end + timedelta(days=1)]
    segments = []
    cursor = start
    total = Decimal('0')
    denominator = Decimal((full_end - full_start).days + 1)
    for boundary in boundaries:
        days = (boundary - cursor).days
        value = rate * days / denominator
        total += value
        segments.append({'start': cursor.isoformat(), 'end': (boundary - timedelta(days=1)).isoformat(),
                         'days': days, 'monthly_rent': str(rate), 'amount': str(cents(value))})
        cursor = boundary
        for changed, _, value in changes:
            if changed == boundary:
                rate = value
    rounded = cents(total)
    # Reconcile segment rounding to the actual charge total, including February/leap years.
    if segments:
        segments[-1]['amount'] = str(rounded - sum((Decimal(row['amount']) for row in segments[:-1]), Decimal('0')))
    return {'amount': str(rounded), 'start': start.isoformat(), 'end': end.isoformat(),
            'period_days': int(denominator), 'cycle': getattr(contract, 'billing_cycle', None) or 'calendar', 'segments': segments}


def preview_billing(contract, effective, amount, treatment):
    impact = max(contract.start_date, switch_date(contract, effective, treatment))
    start, _ = containing_period(contract, impact)
    return calculate_rent(contract, start.year, start.month,
                          SimpleNamespace(effective_date=effective, new_amount=amount, billing_treatment=treatment))
